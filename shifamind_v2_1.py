    rank = i + 1
    if code not in current_set:
        # Skip Y-codes and Z20-Z29 (external cause / contact/exposure — same issues)
        # Also skip codes starting with V, W, X (external causes of morbidity)
        skip = False
        if code.startswith(("V", "W", "X", "Y")):
            skip = True
        # Z20-Z29 are "contact with" codes — administrative, not clinical
        if code.startswith("Z2") and len(code) >= 3 and code[2].isdigit() and int(code[1:3]) >= 20 and int(code[1:3]) <= 29:
            skip = True

        candidates.append({
            "rank": rank,
            "icd_code": code,
            "count": int(count),
            "skipped": skip,
            "skip_reason": "External cause / contact code" if skip else "",
        })
        shown += 1
        if shown <= 20:
            flag = " ← SKIP (external/contact)" if skip else " ✓ CANDIDATE"
            print(f"    Rank #{rank}: {code:>10s}  count={count:>7,}{flag}")
    if shown >= 20:
        break

