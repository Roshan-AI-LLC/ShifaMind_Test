# ============================================================================
# MODEL — Pure MCB with BioClinical ModernBERT
# ============================================================================

class ShifaMindMCB(nn.Module):
    """
    Multiplicative Concept Bottleneck (MCB) with BioClinical ModernBERT.

    Forward pass:
      1. ModernBERT encodes discharge summary → H [B, L, 768]
      2. CLS pool → pooled_text [B, 768]
      3. Concept embeddings attend to H (cross-attention) → Z_c [B, |C|, 768]
      4. Mean-pool Z_c → pooled_context [B, 768]  (concept-grounded text repr)
      5. Concept head predicts concept scores from pooled_text
      6. Gate net: [pooled_text ⊕ pooled_context] → gate [B, 768]
      7. Bottleneck = gate ⊙ pooled_context  (multiplicative — NOT additive)
      8. LayerNorm → diagnosis head → logits [B, 50]
    """

    def __init__(self, num_concepts: int, num_labels: int, attn_impl: str = "sdpa"):
        super().__init__()

        # --- Backbone --------------------------------------------------------
        self.encoder = AutoModel.from_pretrained(
            MODEL_NAME,
            attn_implementation=attn_impl,
        )

        # --- Concept embeddings (randomly initialised, trained end-to-end) ---
        self.concept_embeddings = nn.Embedding(num_concepts, HIDDEN_SIZE)
        nn.init.xavier_uniform_(self.concept_embeddings.weight)

        # --- Cross-attention: concept queries attend to token keys/values ----
        # Q = concept embeddings [B, |C|, 768]
        # K = V = token representations H [B, L, 768]
        self.cross_attn = nn.MultiheadAttention(
            embed_dim=HIDDEN_SIZE,
            num_heads=NUM_HEADS,
            batch_first=True,
            dropout=0.1,
        )

        # --- Concept head: text pool → concept logits [B, |C|] ---------------
        self.concept_head = nn.Linear(HIDDEN_SIZE, num_concepts)

        # --- Gate network: [pooled_text ⊕ pooled_context] → gate [B, 768] ---
        # Two-layer MLP: 1536 → 768 (ReLU) → 768 (Sigmoid)
        self.gate_net = nn.Sequential(
            nn.Linear(HIDDEN_SIZE * 2, HIDDEN_SIZE),
            nn.ReLU(),
            nn.Linear(HIDDEN_SIZE, HIDDEN_SIZE),
            nn.Sigmoid(),
        )

        # --- Bottleneck LayerNorm -------------------------------------------
        self.bottleneck_norm = nn.LayerNorm(HIDDEN_SIZE)

        # --- Diagnosis head: bottleneck → diagnosis logits [B, 50] -----------
        self.diagnosis_head = nn.Linear(HIDDEN_SIZE, num_labels)

    def forward(self, input_ids, attention_mask):
        B = input_ids.size(0)

        # 1. Encode text
        enc_out = self.encoder(
            input_ids=input_ids,
            attention_mask=attention_mask,
        )
        H = enc_out.last_hidden_state  # [B, L, 768]

        # 2. CLS token pool
        pooled_text = H[:, 0, :]  # [B, 768]

        # 3. Cross-attention: concepts attend to tokens
        #    key_padding_mask: True = ignore (padding), False = attend (real token)
        key_padding_mask = (attention_mask == 0)  # [B, L]

        concept_queries = self.concept_embeddings.weight.unsqueeze(0).expand(B, -1, -1)
        # [B, num_concepts, 768]

        Z_c, _ = self.cross_attn(
            query=concept_queries,
            key=H,
            value=H,
            key_padding_mask=key_padding_mask,
        )
        # Z_c: [B, num_concepts, 768] — each concept grounded to relevant tokens

        # 4. Mean-pool concept representations → context vector
        pooled_context = Z_c.mean(dim=1)  # [B, 768]

        # 5. Concept logits (from text pool, not from Z_c — fast, sufficient)
        concept_logits = self.concept_head(pooled_text)  # [B, num_concepts]

        # 6. Gate: combine text and concept-grounded representations
        gate_input = torch.cat([pooled_text, pooled_context], dim=-1)  # [B, 1536]
        gate = self.gate_net(gate_input)                                 # [B, 768]

        # 7. Multiplicative bottleneck (NOT additive — preserves interpretability)
        bottleneck = gate * pooled_context     # [B, 768]
        bottleneck = self.bottleneck_norm(bottleneck)

        # 8. Diagnosis logits
        diagnosis_logits = self.diagnosis_head(bottleneck)  # [B, 50]

        return {
            "diagnosis_logits": diagnosis_logits,    # [B, num_labels]
            "concept_logits":   concept_logits,      # [B, num_concepts]
            "concept_repr":     pooled_context,      # [B, 768] — for alignment loss
            "text_repr":        pooled_text,         # [B, 768] — for alignment loss
        }


# ============================================================================
# LOSS
# ============================================================================

def focal_loss(logits, targets, gamma=FOCAL_GAMMA, alpha=FOCAL_ALPHA):
    """
    Sigmoid Focal Loss for multi-label classification.
    Handles class imbalance by down-weighting easy examples.
      FL = -alpha * (1 - p)^gamma * log(p)       for positives
         - (1-alpha) * p^gamma * log(1-p)         for negatives
    """
    bce = F.binary_cross_entropy_with_logits(logits, targets, reduction="none")
    p_t = torch.exp(-bce)                           # probability of correct class
    alpha_t = alpha * targets + (1 - alpha) * (1 - targets)
    focal_weight = alpha_t * (1 - p_t) ** gamma
    return (focal_weight * bce).mean()


def compute_loss(outputs, diagnosis_labels, concept_labels):
    """
    Multi-task loss:
      L = λ_diag * L_diag + λ_align * L_align + λ_concept * L_concept

      L_diag    = FocalLoss(γ=2, α=0.75) — handles ICD-10 label imbalance
      L_concept = BCE(concept_logits, concept_labels)
      L_align   = 1 - cosine_similarity(concept_repr, text_repr).mean()
    """
    L_diag = focal_loss(outputs["diagnosis_logits"], diagnosis_labels)
    L_concept = F.binary_cross_entropy_with_logits(
        outputs["concept_logits"], concept_labels
    )
    L_align = (
        1.0 - F.cosine_similarity(
            outputs["concept_repr"], outputs["text_repr"], dim=-1
        ).mean()
    )

    total = LAMBDA_DIAG * L_diag + LAMBDA_ALIGN * L_align + LAMBDA_CONCEPT * L_concept

    return total, {
        "total":   total.item(),
        "diag":    L_diag.item(),
        "concept": L_concept.item(),
        "align":   L_align.item(),
    }


# ============================================================================
# EVALUATION
# ============================================================================

@torch.no_grad()
def evaluate(model, loader, desc="Val"):
    model.eval()
    all_logits, all_labels = [], []

    for batch in tqdm(loader, desc=f"  {desc}", leave=False):
        input_ids      = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        dx_labels      = batch["diagnosis_labels"]

        with torch.autocast(device_type="cuda", dtype=torch.bfloat16):
            out = model(input_ids, attention_mask)
        all_logits.append(torch.sigmoid(out["diagnosis_logits"]).float().cpu().numpy())
        all_labels.append(dx_labels.numpy())

    probs  = np.vstack(all_logits)   # [N, NUM_LABELS]
    labels = np.vstack(all_labels)   # [N, NUM_LABELS]
    preds  = (probs > 0.5).astype(int)

    macro_f1 = float(f1_score(labels, preds, average="macro",  zero_division=0))
    micro_f1 = float(f1_score(labels, preds, average="micro",  zero_division=0))

    model.train()
    return macro_f1, micro_f1, probs, labels


