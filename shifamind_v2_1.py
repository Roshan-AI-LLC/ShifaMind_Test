    for step, batch in enumerate(pbar):
        input_ids      = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        dx_labels      = batch["diagnosis_labels"].to(device)
        c_labels       = batch["concept_labels"].to(device)

