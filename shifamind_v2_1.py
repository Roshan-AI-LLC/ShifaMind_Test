SCOPE_TERMINATORS_RE = re.compile(r"[.;\n]|\b(but|however|although|yet)\b", re.IGNORECASE)
SCOPE_WINDOW = 6


def _check_negation(sentence: str, concept: str) -> bool:
    sent_lower = sentence.lower()
    matches = list(re.finditer(r"\b" + re.escape(concept) + r"\b", sent_lower))
    if not matches:
        return False

    tokens = sent_lower.split()
    char_pos = 0
    token_starts = []
    for tok in tokens:
        token_starts.append(char_pos)
        char_pos += len(tok) + 1

    for match in matches:
        concept_start_char = match.start()
        concept_tok_idx = 0
        for i, ts in enumerate(token_starts):
            if ts <= concept_start_char:
                concept_tok_idx = i

        pre_text = " ".join(tokens[max(0, concept_tok_idx - SCOPE_WINDOW):concept_tok_idx])
        post_text = " ".join(tokens[concept_tok_idx + 1:
                                     min(len(tokens), concept_tok_idx + SCOPE_WINDOW + 1)])

        pre_scope = SCOPE_TERMINATORS_RE.search(pre_text)
        if pre_scope:
            pre_text = pre_text[pre_scope.end():]
        post_scope = SCOPE_TERMINATORS_RE.search(post_text)
        if post_scope:
            post_text = post_text[:post_scope.start()]

        local_context = pre_text + " " + post_text
        if any(p in local_context for p in PSEUDO_NEGATION_TRIGGERS):
            return False

        pre_negated  = any(t in pre_text  for t in PRE_NEGATION_TRIGGERS)
        post_negated = any(t in post_text for t in POST_NEGATION_TRIGGERS)

        if not pre_negated and not post_negated:
            return False

    return True


def is_concept_present(text: str, concept: str) -> int:
    text_lower = text.lower()
    if not re.search(r"\b" + re.escape(concept) + r"\b", text_lower):
        return 0
    for sentence in re.split(r"[.\n;]+", text_lower):
        sentence = sentence.strip()
        if not sentence:
            continue
        if not re.search(r"\b" + re.escape(concept) + r"\b", sentence):
            continue
        if not _check_negation(sentence, concept):
            return 1
    return 0


def generate_concept_labels(texts: list[str], concepts: list[str]) -> np.ndarray:
    labels = []
    for text in tqdm(texts, desc="  Concept labels", leave=False, mininterval=2.0):
        labels.append([is_concept_present(str(text), c) for c in concepts])
    return np.array(labels, dtype=np.float32)


def generate_naive_labels(texts: list[str], concepts: list[str]) -> np.ndarray:
    labels = []
    for text in tqdm(texts, desc="  Naive labels", leave=False, mininterval=2.0):
        tl = str(text).lower()
        labels.append([1 if re.search(r"\b" + re.escape(c) + r"\b", tl) else 0
                        for c in concepts])
    return np.array(labels, dtype=np.float32)


